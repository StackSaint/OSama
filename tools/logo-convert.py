#!/usr/bin/env python3
"""Convert an image into the OSama boot logo header (user/osama-logo.h).

The logo is drawn by the shell in VGA text mode with code page 437
half-block characters, so one text cell holds two vertical pixels:

    top+bottom -> 0xDB (full block)   top only -> 0xDF (upper half)
    bottom only -> 0xDC (lower half)  none -> space

The default 28 x 32 pixel grid (28 columns x 16 rows) looks square on screen,
because one half-block pixel is 9 x 8 screen pixels.

Usage:
    python tools/logo-convert.py osama.jpg user/osama-logo.h
    python tools/logo-convert.py osama.jpg user/osama-logo.h --ffmpeg /path/to/ffmpeg
"""

import argparse
import shutil
import subprocess
import sys

BLOCKS = {(1, 1): "\\xDB", (1, 0): "\\xDF", (0, 1): "\\xDC", (0, 0): " "}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("image", help="input image (jpg/png)")
    parser.add_argument("output", help="output C header")
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg") or "ffmpeg",
                        help="path to the ffmpeg executable")
    parser.add_argument("--width", type=int, default=28)
    parser.add_argument("--height", type=int, default=32)
    parser.add_argument("--threshold", type=int, default=128,
                        help="gray level (0-255) treated as foreground")
    args = parser.parse_args()
    if args.height % 2 != 0:
        parser.error("height must be even (two pixels per text cell)")

    command = [
        args.ffmpeg, "-v", "error", "-i", args.image,
        "-vf", f"scale={args.width}:{args.height}:flags=area,format=gray",
        "-frames:v", "1", "-f", "rawvideo", "-",
    ]
    raw = subprocess.run(command, stdout=subprocess.PIPE, check=True).stdout
    if len(raw) < args.width * args.height:
        sys.exit("ffmpeg produced too little data")
    bits = [1 if value >= args.threshold else 0 for value in raw]

    rows = []
    for row in range(args.height // 2):
        top = bits[(row * 2) * args.width:(row * 2 + 1) * args.width]
        bottom = bits[(row * 2 + 1) * args.width:(row * 2 + 2) * args.width]
        rows.append("".join(BLOCKS[(t, b)] for t, b in zip(top, bottom)))

    with open(args.output, "w", newline="\n") as out:
        out.write("/* Generated by tools/logo-convert.py from the OSama logo image.\n")
        out.write(" * Each row uses CP437 half blocks (two pixels per text cell). */\n")
        out.write("#ifndef _OSAMA_LOGO_H\n#define _OSAMA_LOGO_H\n\n")
        out.write(f"#define OSAMA_LOGO_WIDTH {args.width}u\n")
        out.write(f"#define OSAMA_LOGO_ROWS  {len(rows)}u\n\n")
        out.write("static const char *const osama_logo[OSAMA_LOGO_ROWS] = {\n")
        for text in rows:
            out.write(f'    "{text}",\n')
        out.write("};\n\n#endif\n")

    for row in range(args.height // 2):
        top = bits[(row * 2) * args.width:(row * 2 + 1) * args.width]
        bottom = bits[(row * 2 + 1) * args.width:(row * 2 + 2) * args.width]
        print("".join({(1, 1): "#", (1, 0): "'", (0, 1): ".", (0, 0): " "}[(t, b)]
                      for t, b in zip(top, bottom)))


if __name__ == "__main__":
    main()
